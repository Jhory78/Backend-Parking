-- Parking spaces (Sprint 2: RF-16 to RF-22).
-- Capacity is loaded here; no user story asks to manage spaces from the app.
CREATE TABLE parking_spaces (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(10) NOT NULL UNIQUE,
    vehicle_type VARCHAR(20) NOT NULL,
    status       VARCHAR(20) NOT NULL,
    version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT parking_spaces_vehicle_type_check CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE')),
    CONSTRAINT parking_spaces_status_check CHECK (status IN ('AVAILABLE', 'OCCUPIED'))
);

