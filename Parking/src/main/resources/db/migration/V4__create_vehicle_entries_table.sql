-- Vehicle entries and exits by plate (Sprint 3: RF-01 to RF-11).

-- The space map shows which registered vehicle is parked in each space and since when.
-- Both columns stay NULL when the space is free or was occupied by hand.
ALTER TABLE parking_spaces ADD COLUMN current_plate VARCHAR(10);
ALTER TABLE parking_spaces ADD COLUMN occupied_since TIMESTAMP WITH TIME ZONE;
ALTER TABLE parking_spaces ADD CONSTRAINT parking_spaces_current_plate_check
    CHECK (current_plate IS NULL OR status = 'OCCUPIED');

CREATE TABLE vehicle_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate        VARCHAR(10)              NOT NULL,
    vehicle_type VARCHAR(20)              NOT NULL,
    space_id     BIGINT                   NOT NULL REFERENCES parking_spaces (id),
    entry_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    exit_time    TIMESTAMP WITH TIME ZONE,
    status       VARCHAR(20)              NOT NULL,
    -- Copy of the plate while the entry is ACTIVE, NULL once CLOSED. UNIQUE allows many NULLs,
    -- so this is a "one active entry per plate" rule that works in PostgreSQL and H2
    -- (H2 has no partial indexes).
    active_plate VARCHAR(10) UNIQUE,
    CONSTRAINT vehicle_entries_vehicle_type_check CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE')),
    -- "active_plate IS NOT NULL" is needed: with NULL, "active_plate = plate" is UNKNOWN and a CHECK accepts UNKNOWN
    CONSTRAINT vehicle_entries_status_check CHECK (
        (status = 'ACTIVE' AND active_plate IS NOT NULL AND active_plate = plate AND exit_time IS NULL)
        OR (status = 'CLOSED' AND active_plate IS NULL AND exit_time IS NOT NULL)
    )
);

CREATE INDEX vehicle_entries_plate_idx ON vehicle_entries (plate);
CREATE INDEX vehicle_entries_status_entry_time_idx ON vehicle_entries (status, entry_time);
