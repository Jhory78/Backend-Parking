-- Users table as Hibernate generated it during Sprint 1 (Spanish column names).
-- Databases created before Flyway was introduced are baselined at version 1,
-- so this script only runs on empty databases. V2 translates the schema.
CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(255) NOT NULL,
    correo   VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol      VARCHAR(255) NOT NULL,
    activo   BOOLEAN      NOT NULL
);
